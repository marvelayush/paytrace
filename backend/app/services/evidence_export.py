"""Evidence export for a claim: a CSV with every order and its source rows, and a one-glance PDF summary."""

from datetime import date, datetime

from fpdf import FPDF

from app.services.csv_safe import csv_text

REASON_LABELS = {
    "short_paid": "Short paid",
    "unpaid_past_due": "Unpaid, past due",
    "freight_overcharged": "Freight overcharged",
    "return_not_received": "Return not received",
    "settled": "Settled",
    "pending": "Not yet due",
}


def rupees(paise: int | None) -> str:
    """Rs 1,23,456.00 in Indian grouping. The PDF's built-in fonts have no ₹ sign, so 'Rs' is used there."""
    if paise is None:
        return "-"
    sign = "-" if paise < 0 else ""
    whole, fraction = divmod(abs(paise), 100)
    digits = str(whole)
    if len(digits) > 3:
        head, tail = digits[:-3], digits[-3:]
        groups = []
        while len(head) > 2:
            groups.insert(0, head[-2:])
            head = head[:-2]
        if head:
            groups.insert(0, head)
        digits = ",".join(groups) + "," + tail
    return f"{sign}Rs {digits}.{fraction:02d}"


def evidence_csv(claim: dict, items: list[dict], sources: dict[str, list[str]]) -> str:
    header = [
        "claim_id", "partner", "order_id", "channel", "order_date", "reason", "expected_inr", "received_inr",
        "difference_inr", "claimed_inr", "due_date", "days_overdue", "source_rows",
    ]
    rows = [
        [
            claim["id"], claim["partner_name"], item["order_id"], item["channel"], item["order_date"],
            REASON_LABELS.get(item["reason_status"], item["reason_status"]),
            f"{(item['expected_paise'] or 0) / 100:.2f}", f"{(item['received_paise'] or 0) / 100:.2f}",
            f"{(item['diff_paise'] or 0) / 100:.2f}", f"{item['amount_paise'] / 100:.2f}",
            item["due_date"] or "", item["age_days"] if item["age_days"] is not None else "",
            "; ".join(sources.get(item["order_id"], [])),
        ]
        for item in items
    ]
    return csv_text(header, rows)


class _ClaimPDF(FPDF):
    def __init__(self, title: str) -> None:
        super().__init__(orientation="P", unit="mm", format="A4")
        self.title_text = title
        self.set_auto_page_break(auto=True, margin=16)
        self.set_margins(14, 14, 14)

    def footer(self) -> None:
        self.set_y(-12)
        self.set_font("Helvetica", size=7.5)
        self.set_text_color(120, 120, 130)
        self.cell(0, 5, f"{self.title_text}  |  Generated by PayTrace  |  Page {self.page_no()}/{{nb}}", align="C")


def _day(value: object) -> str:
    if isinstance(value, datetime | date):
        return value.strftime("%d %b %Y")
    if isinstance(value, str) and value:
        return datetime.fromisoformat(value).strftime("%d %b %Y")
    return "-"


def evidence_pdf(claim: dict, items: list[dict], generated_on: date) -> bytes:
    title = f"Claim #{claim['id']} - {claim['partner_name']}"
    pdf = _ClaimPDF(title)
    pdf.alias_nb_pages()
    pdf.add_page()
    ink, muted, loss, rule = (24, 24, 32), (110, 110, 122), (200, 30, 30), (225, 225, 232)

    pdf.set_text_color(*ink)
    pdf.set_font("Helvetica", "B", 16)
    pdf.cell(0, 9, title, new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", size=9)
    pdf.set_text_color(*muted)
    meta = f"Status: {claim['status'].capitalize()}   |   Opened {_day(claim['created_at'])}   |   Prepared {_day(generated_on)}"
    if claim.get("reference"):
        meta += f"   |   Partner reference {claim['reference']}"
    pdf.cell(0, 5, meta, new_x="LMARGIN", new_y="NEXT")
    pdf.ln(4)

    # Headline figure
    pdf.set_draw_color(*rule)
    pdf.set_fill_color(250, 245, 245)
    pdf.set_font("Helvetica", size=9)
    pdf.set_text_color(*muted)
    pdf.cell(0, 6, "Amount claimed", new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "B", 20)
    pdf.set_text_color(*loss)
    pdf.cell(0, 10, rupees(claim["total_paise"]), new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", size=9)
    pdf.set_text_color(*muted)
    pdf.cell(0, 5, f"across {len(items)} orders. Every amount is checked against the agreed rate card; tax withheld (TCS/TDS) is not claimed.",
             new_x="LMARGIN", new_y="NEXT")
    pdf.ln(5)

    # Summary by reason
    pdf.set_text_color(*ink)
    pdf.set_font("Helvetica", "B", 10)
    pdf.cell(0, 6, "Summary", new_x="LMARGIN", new_y="NEXT")
    by_reason: dict[str, list[int]] = {}
    for item in items:
        by_reason.setdefault(item["reason_status"], []).append(item["amount_paise"])
    pdf.set_font("Helvetica", size=9)
    for reason, amounts in sorted(by_reason.items(), key=lambda entry: -sum(entry[1])):
        pdf.cell(90, 6, REASON_LABELS.get(reason, reason), border="B")
        pdf.cell(30, 6, f"{len(amounts)} orders", border="B", align="R")
        pdf.cell(0, 6, rupees(sum(amounts)), border="B", align="R", new_x="LMARGIN", new_y="NEXT")
    pdf.ln(6)

    # Item table (widths add up to the 182 mm between A4 margins)
    columns = [("Order", 32, "L"), ("Reason", 36, "L"), ("Expected", 26, "R"), ("Received", 26, "R"), ("Claimed", 26, "R"), ("Due", 22, "R"), ("Overdue", 14, "R")]

    def table_header() -> None:
        pdf.set_font("Helvetica", "B", 8.5)
        pdf.set_text_color(*muted)
        for label, width, align in columns:
            pdf.cell(width, 6, label, border="B", align=align)
        pdf.ln()
        pdf.set_font("Helvetica", size=8.5)
        pdf.set_text_color(*ink)

    table_header()
    for item in items:
        if pdf.will_page_break(5.5):
            pdf.add_page()
            table_header()  # repeat the column names on every page
        values = [
            item["order_id"], REASON_LABELS.get(item["reason_status"], item["reason_status"]), rupees(item["expected_paise"]),
            rupees(item["received_paise"]), rupees(item["amount_paise"]), _day(item["due_date"]),
            "" if item["age_days"] is None else str(item["age_days"]),
        ]
        for (_, width, align), value in zip(columns, values):
            pdf.cell(width, 5.5, value, border="B", align=align)
        pdf.ln()

    pdf.ln(4)
    pdf.set_font("Helvetica", size=7.5)
    pdf.set_text_color(*muted)
    pdf.multi_cell(0, 4, "The accompanying CSV lists, for every order, the partner report file and row number each figure came from. "
                         "Customer personal data is masked and not included.")
    return bytes(pdf.output())
